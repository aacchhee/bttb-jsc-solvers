def _apply(F, A, x, lo, hi):
    out = []
    for row in A:
        value = {}
        for a, b in zip(row, x):
            if not a or not b:
                continue
            value = sa(F, value, sm(F, a, b, lo, hi), lo, hi)
        out.append(value)
    return out


def _series(F, vector, n, length):
    out = [{} for _ in range(n)]
    for t in range(length):
        for i in range(n):
            value = vector[t*n+i]
            if not F.is_zero(value):
                out[i][t] = value
    return out


def packed_terminal(F, joint, n, w):
    """Return a lag accessor and O(n+q) coordinate metadata, never a matrix."""
    delta = joint['delta']
    channels = [('p', i) for i in range(n)]
    channels += [('a', i) for i, de in enumerate(delta) if de > 0]
    lengths = [w]*n + [de for de in delta if de > 0]
    def coefficient(i, j, lag):
        typ, r = channels[i]
        kind, s = channels[j]
        if typ == kind == 'p':
            return joint['W'][r][s].get(n+lag, F.zero())
        if typ == 'p':
            return joint['B'][r][s].get(delta[s]-w+lag, F.zero())
        if kind == 'p':
            return F.neg(joint['G'][r][s].get(lag, F.zero()))
        return F.zero()
    h = n*w
    shuffle = [t*n+r for r in range(n) for t in range(w)]
    shuffle += list(range(h, h+sum(delta)))
    return {'chain_lengths': lengths, 'chain_ids': channels,
            'physical_shuffle': shuffle}, coefficient


def reconstruct(F, joint, terminal, backend, rhs, n, w):
    """Apply W/G/B convolutions and head/tail selectors directly."""
    if len(rhs) != n*n:
        raise ValueError('RHS must have n*n physical time-major entries')
    L = n+w
    delta = joint['delta']
    dmax = max(delta, default=0)
    f = [F.zero()]*(n*w) + list(rhs)
    fs = _series(F, f, n, L)
    Wf = _apply(F, joint['W'], fs, -dmax, L)
    Gf = _apply(F, joint['G'], fs, 0, L+dmax)
    dtime = [F.neg(Wf[r].get(t, F.zero()))
             for t in range(n, L) for r in range(n)]
    dtime += [Gf[i].get(t, F.zero())
              for i, de in enumerate(delta) for t in range(de)]
    shuffle = terminal['physical_shuffle']
    dchain = [dtime[i] for i in shuffle]
    affine = solve_mosaic(F, backend, dchain)
    solution = affine['solution']
    if solution is None:
        raise ArithmeticError('nonsingular terminal affine basis lacks readout')
    time_solution = [F.zero()]*len(solution)
    for i, target in enumerate(shuffle):
        time_solution[target] = solution[i]
    u, sigma = time_solution[:n*w], time_solution[n*w:]
    y = list(f)
    for i, value in enumerate(u):
        y[i] = F.add(y[i], value)
    ys = _series(F, y, n, L)
    Wy = _apply(F, joint['W'], ys, -dmax, L)
    kernels = [{} for _ in delta]
    at = 0
    for i, de in enumerate(delta):
        for b in range(de):
            value = sigma[at]
            at += 1
            if not F.is_zero(value):
                kernels[i][L-de+b] = value
    BK = _apply(F, joint['B'], kernels, 0, L)
    xseries = [sa(F, Wy[i], BK[i], -dmax, L) for i in range(n)]
    negative = [{k: v for k, v in s.items() if k < 0} for s in xseries]
    for series in negative:
        if any(not F.is_zero(value) for value in series.values()):
            raise ArithmeticError('physical reconstruction has negative support')
    xfull = [xseries[r].get(t, F.zero()) for t in range(L) for r in range(n)]
    tail = xfull[n*n:]
    if any(not F.is_zero(value) for value in tail):
        raise ArithmeticError('physical reconstruction has nonzero tail')
    Gy = _apply(F, joint['G'], ys, 0, L+dmax)
    tau = [F.add(sigma[a], Gy[i].get(L+b, F.zero()))
           for a, (i, b) in enumerate((i, b) for i, de in enumerate(delta)
                                     for b in range(de))]
    physical = xfull[:n*n]
    return {'b': list(rhs), 'f': f, 'terminal_rhs_time': dtime,
            'terminal_rhs': dchain, 'affine': affine,
            'terminal_solution': solution, 'u': u, 'sigma': sigma, 'tau': tau,
            'y': y, 'xseries': xseries, 'xfull': xfull,
            'physical_solution': physical,
            'physical_solution_base': [descend(F, x) for x in physical],
            'negative_coefficients': negative, 'tail': tail}


def _default_rhs(F, blocks, n, w):
    """Reference fixture cases, generated by polynomial products, not dense T."""
    A = [[{} for _ in range(n)] for _ in range(n)]
    for d, block in enumerate(blocks):
        for i in range(n):
            for j in range(n):
                A[i][j][d] = block[i][j]
    N = n*n
    prescribed = [[F.one() if i == 0 else F.zero() for i in range(N)],
                  [F.from_int(i+1) for i in range(N)]]
    cases = []
    for vector in prescribed:
        product = _apply(F, A, _series(F, vector, n, n), 0, n+w)
        cases.append([product[i].get(t+w, F.zero())
                      for t in range(n) for i in range(n)])
    cases.append([F.from_int(t*t+3*t+1) for t in range(N)])
    return cases, prescribed


def _validate_input(blocks, n, w, rhs=None):
    if type(n) is not int or type(w) is not int or n < 2 or not 1 <= w < n:
        raise ValueError('scope requires integers n >= 2 and 1 <= w < n')
    if not blocks or len(blocks) > n+w or any(len(B) != n or any(len(r) != n for r in B) for B in blocks):
        raise ValueError('coefficient blocks must be n-by-n and have degree < n+w')
    if rhs is not None and len(rhs) != n*n:
        raise ValueError('RHS must have n*n physical time-major entries')


class _ReadSeries:
    """Read-only Mapping protocol; records degrees actually visited by consumer.

    The probe observes source reads, including enumeration before truncation.
    It does not claim every visited coefficient affects the final answer.
    """
    def __init__(self,values,probe,name): self.values,self.probe,self.name=values,probe,name
    def _record(self,k,operation,present):
        p=self.probe;tag=self.name+':'+str(k)
        p['read_counts'][tag]=p['read_counts'].get(tag,0)+1
        if present:p['present_read_counts'][tag]=p['present_read_counts'].get(tag,0)+1
        p['operations'][operation]=p['operations'].get(operation,0)+1
        p['max_degree']=k if p['max_degree'] is None else max(p['max_degree'],k)
    def __len__(self):return len(self.values)
    def __iter__(self):
        for k in self.values:
            self._record(k,'iteration',True)
            yield k
    def __getitem__(self,k):
        self._record(k,'getitem',k in self.values)
        return self.values[k]
    def __contains__(self,k):
        self._record(k,'contains',k in self.values)
        return k in self.values
    def keys(self):return iter(self)
    def items(self):
        for k,v in self.values.items():
            self._record(k,'items',True)
            yield k,v
    def get(self,k,default=None):
        self._record(k,'get',k in self.values)
        return self.values.get(k,default)


def _trace_carrier(c,probe):
    for name in ('H','R','BA','BV','S'):
        c[name]=[[_ReadSeries(x,probe,name) for x in row] for row in c[name]]


def solve(F, blocks, n, w, rhs=None, labels=None, *, rhs_cases=None,
          fixture_cases=False, terminal_backend='uniform_fast',
          precision_mode='full', precision_probe=False):
    """Solve embedded blocks and one RHS (or explicit RHS cases) over F.

    Labels must be n distinct nonzero field elements. If omitted, 1,...,n
    are used; small-characteristic callers should use run_fixture or supply
    labels from their guarded extension. Restart propagates to the caller.
    terminal_backend explicitly selects the existing classical or uniform_fast
    mosaic engine; affine reconstruction inherits that same backend. The
    historical default remains uniform_fast.
    """
    _validate_input(blocks, n, w, rhs)
    if terminal_backend not in ('classical', 'uniform_fast'):
        raise ValueError('terminal_backend must be classical or uniform_fast')
    if labels is None:
        labels = [F.from_int(i+1) for i in range(n)]
    if len(labels) != n:
        raise ValueError('exactly n distinct nonzero labels required')
    for i, label in enumerate(labels):
        if F.is_zero(label) or any(F.is_zero(F.sub(label, previous)) for previous in labels[:i]):
            raise ValueError('distinct nonzero labels required; use run_fixture for automatic field setup')
    if rhs is not None and rhs_cases is not None:
        raise ValueError('supply rhs or rhs_cases, not both')
    L = n+w
    if precision_mode not in ('full', 'q0_L'):
        raise ValueError('precision_mode must be full or q0_L')
    if precision_mode == 'q0_L':
        from .exact import kernel
        ker = kernel(F,list(reversed(blocks[0])))
        if ker and len(ker[0]):
            raise ValueError('q0_L is an opt-in q=0 arm; q>0 retains full precision')
    precision = L if precision_mode == 'q0_L' else L+3*n*w
    c = carrier(F, blocks, labels, precision)
    probe = {'scope':'carrier coefficient reads by joint compiler only',
             'source_precision':precision,'read_counts':{},'present_read_counts':{},
             'operations':{},'max_degree':None}
    if precision_probe:
        _trace_carrier(c,probe)
    j = joint_compiler(F, c, n, w)
    if precision_mode == 'q0_L':
        j['P'] = L  
    precision_metadata = {'mode':precision_mode,'source_precision':precision,
                          'q':c['q'],'q_positive_bound_reduced':False}

    out = {'carrier': c, 'joint': j, 'rhs': [], 'solution': None, 'stage': 'joint',
           'precision':precision_metadata,
           'precision_probe':probe if precision_probe else None,
           'embedding_descent': {
               'embedding': 'base element is constant coordinate in retained power basis',
               'descent': 'check nonconstant coordinates vanish, then extract coordinate zero',
               'modulus': F.modulus if isinstance(F, EtaleField) else None}}
    if j['overcap']:
        zero = F.base.zero() if isinstance(F, EtaleField) else F.zero()
        out.update(det=F.zero(), det_base=zero, singular=True,
                   stage='complete_overcap', field_final=F.info())
        return out
    terminal, access = packed_terminal(F, j, n, w)
    exponent = n*n*(n*w)+sum(de*(L-de) for de in j['delta'])
    ratio = F.mul(c['H0_det'], F.inv(F.mul(j['dU'], j['dV'])))
    gamma = power(F, ratio, L)
    if exponent % 2:
        gamma = F.neg(gamma)
    backend = run_mosaic(F, terminal['chain_lengths'], access, backend=terminal_backend)
    terminal['backend'] = backend
    det = F.mul(gamma, backend['det'])
    singular = F.is_zero(det)
    out.update(terminal=terminal, gamma=gamma, gamma_exponent=exponent,
               det=det, det_base=descend(F, det), singular=singular)
    if not singular:
        prescribed = []
        if fixture_cases and rhs is None and rhs_cases is None:
            cases, prescribed = _default_rhs(F, blocks, n, w)
        else:
            cases = list(rhs_cases) if rhs_cases is not None else ([] if rhs is None else [rhs])
        for index, b in enumerate(cases):
            rec = reconstruct(F, j, terminal, backend, b, n, w)
            rec['rhs_index'] = index+1
            rec['prescribed_solution'] = prescribed[index] if index < len(prescribed) else None
            out['rhs'].append(rec)
    out.update(stage='complete', field_final=F.info())
    out['solution'] = out['rhs'][0]['physical_solution_base'] if out['rhs'] else None
    return out


def run_fixture(fixture, rhs=None, *, fixture_cases=True):
    """Raw fixture entry; optional RHS is a raw named-base physical vector.

    Any Restart discards carrier, joint, mosaic, determinant and RHS state,
    rebuilds labels/blocks from the raw fixture, and reruns the whole pipeline.
    """
    _validate_input(fixture['blocks'], fixture['n'], fixture['w'], rhs)
    restriction = None
    restarts = []
    attempt = 0
    while True:
        F, blocks, labels, meta = setup_field(fixture, restriction)
        attempt += 1
        try:
            embedded_rhs = None
            if rhs is not None:
                base = F.base if isinstance(F, EtaleField) else F
                embedded_rhs = [raw_scalar(base, fixture['field'], x) for x in rhs]
                if isinstance(F, EtaleField):
                    embedded_rhs = [F.embed(x) for x in embedded_rhs]
            result = solve(F, blocks, fixture['n'], fixture['w'], embedded_rhs,
                           labels, fixture_cases=fixture_cases and rhs is None)
            result.update(fixture=fixture, field_setup=meta, restarts=restarts,
                          attempt=attempt)
            return result
        except Restart as event:
            restarts.append({'attempt': attempt, 'old_modulus': F.modulus,
                'expression': event.expression, 'gcd_factor': event.factor,
                'retained_component': event.factor, 'old_degree': F.degree,
                'new_degree': len(event.factor)-1, 'guard_index': event.guard_index,
                'inverse_guards_before_abort': list(F.inverse_guards),
                'invalidated': 'all field-dependent carrier/joint/backend/RHS state',
                'restart_from': 'raw fixture'})
            restriction = event.factor


run_instance = run_fixture


def solve_lags(blocks, w, field="F1000003", rhs=None):
    """Raw Toeplitz lag blocks; automatically construct labels and restart.

    Named fields are Q, F4 (the fixed quadratic binary field), or Fp for a
    caller-supplied prime p. Coefficients and rhs use these named-base scalars.
    Omitting rhs computes the determinant only.
    """
    n = len(blocks[0]) if blocks else 0
    raw = {"id": "solve_lags", "n": n, "w": w, "field": field, "blocks": blocks}
    return run_fixture(raw, rhs=rhs, fixture_cases=False)


def solve_field(base, blocks, w, rhs=None):
    """Automatic determinant/solve over any effective exact-field adapter.

    Coefficients and RHS are existing elements of base and are never converted
    through integers. Only added working-algebra coordinates are descended;
    caller base extensions retain their original element representation.
    Every nonunit in the added algebra restarts from the original base inputs.
    """
    n = len(blocks[0]) if blocks else 0
    _validate_input(blocks, n, w, rhs)
    original_blocks = [[list(row) for row in block] for block in blocks]
    original_rhs = None if rhs is None else list(rhs)
    restriction = None
    restarts = []
    attempt = 0
    while True:
        F, embedded, labels, meta, embed = setup_effective_field(
            base, original_blocks, n, restriction)
        attempt += 1
        try:
            embedded_rhs = (None if original_rhs is None else
                            [embed(value) for value in original_rhs])
            result = solve(F, embedded, n, w, embedded_rhs, labels)
            result.update(field_setup=meta, restarts=restarts, attempt=attempt)
            return result
        except Restart as event:
            restarts.append({'attempt': attempt, 'old_modulus': F.modulus,
                'expression': event.expression, 'gcd_factor': event.factor,
                'retained_component': event.factor, 'old_degree': F.degree,
                'new_degree': len(event.factor)-1, 'guard_index': event.guard_index,
                'inverse_guards_before_abort': list(F.inverse_guards),
                'invalidated': 'all field-dependent carrier/joint/backend/RHS state',
                'restart_from': 'original base-field blocks and RHS'})
            restriction = event.factor
